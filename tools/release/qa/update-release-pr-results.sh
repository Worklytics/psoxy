#!/bin/bash
# Post connector QA summaries to a release PR and check off test-plan items.
# Usage: ./tools/release/qa/update-release-pr-results.sh <pr-number> <aws-checklist-file> <gcp-checklist-file> [aws-summary-md] [gcp-summary-md]
# Checklist files are produced by summarize-connector-tests.sh (*.checklist).

set -euo pipefail

COLORSCHEME_SH="$(dirname "$0")/../../set-term-colorscheme.sh"
if [ -f "$COLORSCHEME_SH" ]; then
  # shellcheck source=/dev/null
  source "$COLORSCHEME_SH"
else
  ERR='\033[0;31m'; SUCCESS='\033[0;32m'; WARN='\033[1;33m'; INFO='\033[0;34m'; NC='\033[0m'
fi

PR_NUMBER="${1:-}"
AWS_CHECKLIST="${2:-}"
GCP_CHECKLIST="${3:-}"
AWS_SUMMARY="${4:-}"
GCP_SUMMARY="${5:-}"

if [ -z "$PR_NUMBER" ] || [ -z "$AWS_CHECKLIST" ] || [ -z "$GCP_CHECKLIST" ]; then
  printf "${ERR}Usage: %s <pr-number> <aws-checklist> <gcp-checklist> [aws-summary-md] [gcp-summary-md]${NC}\n" "$0"
  exit 1
fi

for f in "$AWS_CHECKLIST" "$GCP_CHECKLIST"; do
  if [ ! -f "$f" ]; then
    printf "${ERR}Checklist file not found: %s${NC}\n" "$f"
    exit 1
  fi
done

COMMENT_FILE="$(mktemp)"
BODY_FILE="$(mktemp)"
trap 'rm -f "$COMMENT_FILE" "$BODY_FILE"' EXIT

{
  echo "## Connector QA results (dev examples)"
  echo ""
  if [ -n "$AWS_SUMMARY" ] && [ -f "$AWS_SUMMARY" ]; then
    cat "$AWS_SUMMARY"
    echo ""
  fi
  if [ -n "$GCP_SUMMARY" ] && [ -f "$GCP_SUMMARY" ]; then
    cat "$GCP_SUMMARY"
    echo ""
  fi
  echo "_Generated by \`tools/release/qa/update-release-pr-results.sh\`_"
} > "$COMMENT_FILE"

gh pr comment "$PR_NUMBER" --body-file "$COMMENT_FILE"
printf "${SUCCESS}Posted QA summary comment on PR #%s.${NC}\n" "$PR_NUMBER"

CURRENT_BODY="$(gh pr view "$PR_NUMBER" --json body -q .body)"
printf "%s" "$CURRENT_BODY" > "$BODY_FILE"

python3 - "$BODY_FILE" "$AWS_CHECKLIST" "$GCP_CHECKLIST" <<'PY'
import re
import sys
from pathlib import Path

body_path, aws_path, gcp_path = sys.argv[1:4]
body = Path(body_path).read_text()
aws = {}
gcp = {}
for path, target in ((aws_path, aws), (gcp_path, gcp)):
    for line in Path(path).read_text().splitlines():
        cloud, key, status = line.split()
        target[key] = status

CATEGORY_LABELS = {
    "microsoft": "Microsoft API connector",
    "google_workspace": "Google Workspace API connector",
    "token": "Token-based API connector",
    "async": "API connector with async",
    "webhook": "Webhook collector",
    "bulk": "Bulk connector",
}


def checkbox(status: str) -> str:
    return "[x]" if status in ("pass", "partial") else "[ ]"


def update_section(section_name: str, statuses: dict[str, str], text: str) -> str:
    pattern = rf"(### {re.escape(section_name)}\s.*?Confirm everything worked:\s*)(.*?)(?=\n### |\Z)"
    m = re.search(pattern, text, flags=re.S)
    if not m:
        return text
    header, block = m.group(1), m.group(2)
    new_block = block
    for key, label in CATEGORY_LABELS.items():
        status = statuses.get(key, "skip")
        if status == "skip":
            continue
        checked = checkbox(status)
        new_block = re.sub(
            rf"- \[ \] {re.escape(label)}",
            f"- {checked} {label}",
            new_block,
        )
        new_block = re.sub(
            rf"- \[x\] {re.escape(label)}",
            f"- {checked} {label}",
            new_block,
        )
    return text[: m.start()] + header + new_block + text[m.end() :]


body = update_section("AWS", aws, body)
body = update_section("GCP", gcp, body)
Path(body_path).write_text(body)
PY

gh pr edit "$PR_NUMBER" --body-file "$BODY_FILE"
printf "${SUCCESS}Updated PR #%s description test-plan checkboxes.${NC}\n" "$PR_NUMBER"
